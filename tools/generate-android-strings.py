#!/usr/bin/env python3
"""
Writes the Android launcher/menu labels (res/values*/strings.xml) from the app's translation tables
(src/UrlShortener.UI/i18n/*.json), so Android labels and in-app text never drift apart.

Run after changing a translation:  python3 tools/generate-android-strings.py
The test suite fails if the generated files are out of date.
"""
import json
import pathlib
from xml.sax.saxutils import escape

ROOT = pathlib.Path(__file__).resolve().parent.parent
I18N = ROOT / "src/UrlShortener.UI/i18n"
RES = ROOT / "src/UrlShortener.Android/Resources"

# Android resource name -> key in the JSON tables
STRINGS = {
    "app_name": "App.Title",
    "shorten_link": "Android.ShortenLink",
    "shorten_clipboard": "Android.ShortenClipboard",
    "shorten_clipboard_long": "Android.ShortenClipboardLong",
}

# App language code -> Android resource folder qualifier
QUALIFIERS = {
    "en": "", "es": "es", "cs": "cs", "de": "de", "fr": "fr", "it": "it", "pt-BR": "pt-rBR",
    "pl": "pl", "nl": "nl", "ru": "ru", "uk": "uk", "tr": "tr", "id": "in", "ar": "ar",
    "hi": "hi", "zh-Hans": "b+zh+Hans", "ja": "ja", "ko": "ko",
}


def android_escape(text: str) -> str:
    # XML escaping, then Android's own rules for apostrophes, quotes and a leading @ or ?.
    text = escape(text).replace("'", "\\'").replace('"', '\\"')
    return "\\" + text if text[:1] in ("@", "?") else text


def render(table: dict) -> str:
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- Generated by tools/generate-android-strings.py from src/UrlShortener.UI/i18n. Don't edit by hand. -->",
             "<resources>"]
    for name, key in STRINGS.items():
        lines.append(f'  <string name="{name}">{android_escape(table[key])}</string>')
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def main() -> None:
    english = json.loads((I18N / "en.json").read_text(encoding="utf-8"))
    for code, qualifier in QUALIFIERS.items():
        table = {**english, **json.loads((I18N / f"{code}.json").read_text(encoding="utf-8"))}
        folder = RES / ("values" if not qualifier else f"values-{qualifier}")
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "strings.xml").write_text(render(table), encoding="utf-8")
    print(f"Wrote strings.xml for {len(QUALIFIERS)} languages.")


if __name__ == "__main__":
    main()
