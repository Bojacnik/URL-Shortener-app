#!/usr/bin/env python3
"""
Writes packaging/linux/url-shortener.desktop (the Linux app-menu entry) with names in every language,
taken from the app's translation tables in src/UrlShortener.UI/i18n.

Run after changing a translation:  python3 tools/generate-linux-desktop.py
The test suite fails if the file is out of date.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
I18N = ROOT / "src/UrlShortener.UI/i18n"
OUT = ROOT / "packaging/linux/url-shortener.desktop"

# App language code -> freedesktop locale
LOCALES = {
    "es": "es", "cs": "cs", "de": "de", "fr": "fr", "it": "it", "pt-BR": "pt_BR", "pl": "pl", "nl": "nl",
    "ru": "ru", "uk": "uk", "tr": "tr", "id": "id", "ar": "ar", "hi": "hi", "zh-Hans": "zh_CN", "ja": "ja", "ko": "ko",
}


def localized(field: str, key: str, tables: dict) -> list[str]:
    lines = [f"{field}={tables['en'][key]}"]
    for code, locale in LOCALES.items():
        value = tables[code].get(key)
        if value and value != tables["en"][key]:
            lines.append(f"{field}[{locale}]={value}")
    return lines


def main() -> None:
    tables = {code: json.loads((I18N / f"{code}.json").read_text(encoding="utf-8")) for code in ["en", *LOCALES]}
    lines = [
        "# Generated by tools/generate-linux-desktop.py from src/UrlShortener.UI/i18n. Don't edit by hand.",
        "[Desktop Entry]",
        "Type=Application",
        "Version=1.5",
        *localized("Name", "App.Title", tables),
        *localized("Comment", "Hero.Subtitle", tables),
        "Exec=UrlShortener",
        "Icon=url-shortener",
        "Terminal=false",
        "Categories=Utility;Network;",
        "Keywords=url;link;shorten;short;qr;expand;",
        "StartupWMClass=UrlShortener",
        "Actions=quick;",
        "",
        "[Desktop Action quick]",
        *localized("Name", "Android.ShortenClipboard", tables),
        "Exec=UrlShortener --quick",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
